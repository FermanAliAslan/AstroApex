"""Build the SPICE ephemeris table the AstroApex site reads (data/spice_table.js).

What it does
------------
Uses NASA NAIF CSPICE (through SpiceyPy) and the JPL DE440 planetary ephemeris to compute,
every STEP_HOURS hours, where the Sun and the Earth are as seen from the Moon's centre, in the
Moon body-fixed frame IAU_MOON, corrected for light time and stellar aberration (LT+S).
The browser interpolates this table, so the site gets SPICE results without needing a server.

Kernels (put them in ./kernels, they are NASA public files):
  de440s.bsp    planetary / lunar ephemeris  https://naif.jpl.nasa.gov/pub/naif/generic_kernels/spk/planets/
  naif0012.tls  leap seconds                 https://naif.jpl.nasa.gov/pub/naif/generic_kernels/lsk/
  pck00010.tpc  body orientation and shape   https://naif.jpl.nasa.gov/pub/naif/generic_kernels/pck/

Run:  pip install spiceypy   then   python tools/build_spice_table.py
"""
import base64
import datetime as dt
import json
import os
import sys

import numpy as np
import spiceypy as spice

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KERNELS = ["naif0012.tls", "pck00010.tpc", "de440s.bsp"]
START = dt.datetime(2024, 1, 1)
END = dt.datetime(2041, 1, 1)
STEP_HOURS = 2
FRAME, ABCORR = "IAU_MOON", "LT+S"
EPOCH = dt.datetime(1970, 1, 1)


def load_kernels():
    for name in KERNELS:
        path = os.path.join(ROOT, "kernels", name)
        if not os.path.exists(path):
            sys.exit("Missing kernel: %s (see the header of this file for where to get it)" % path)
        spice.furnsh(path)


def moon_fixed(et):
    """Sun and Earth position (km) relative to the Moon's centre in the Moon-fixed frame."""
    sun, _ = spice.spkpos("SUN", et, FRAME, ABCORR, "MOON")
    earth, _ = spice.spkpos("EARTH", et, FRAME, ABCORR, "MOON")
    return np.asarray(sun), np.asarray(earth)


def catmull_rom(p0, p1, p2, p3, u):
    return 0.5 * ((2 * p1) + (-p0 + p2) * u + (2 * p0 - 5 * p1 + 4 * p2 - p3) * u * u
                  + (-p0 + 3 * p1 - 3 * p2 + p3) * u ** 3)


def main():
    load_kernels()
    step_s = STEP_HOURS * 3600
    n = int((END - START).total_seconds() // step_s) + 1
    et0 = spice.str2et(START.strftime("%Y-%m-%dT%H:%M:%S"))
    et = et0 + np.arange(n) * float(step_s)      # no leap seconds are scheduled, so UTC steps = ET steps
    sun, earth = moon_fixed(et)
    table = np.hstack([sun, earth]).astype("<f4")

    # Self-check: interpolate the stored (float32) table at interval midpoints and compare with SPICE.
    idx = np.arange(1, n - 2, max(1, n // 4000))
    t64 = table.astype(np.float64)
    mid = catmull_rom(t64[idx - 1], t64[idx], t64[idx + 1], t64[idx + 2], 0.5)
    s_mid, e_mid = moon_fixed(et[idx] + step_s / 2)

    def ang(a, b):
        a = a / np.linalg.norm(a, axis=1)[:, None]
        b = b / np.linalg.norm(b, axis=1)[:, None]
        return np.degrees(np.arccos(np.clip((a * b).sum(axis=1), -1, 1)))

    err_sun = float(ang(mid[:, :3], s_mid).max())
    err_earth = float(ang(mid[:, 3:], e_mid).max())

    meta = {
        "source": "NASA NAIF CSPICE %s via SpiceyPy %s" % (spice.tkvrsn("TOOLKIT"), spice.__version__),
        "ephemeris": "JPL DE440 (de440s.bsp)",
        "frame": FRAME, "abcorr": ABCORR, "observer": "MOON", "kernels": KERNELS,
        "t0": int((START - EPOCH).total_seconds() * 1000), "step": step_s * 1000, "n": n,
        "layout": "float32 little-endian, per sample: sun x,y,z then earth x,y,z (km)",
        "maxInterpErrorDeg": {"sun": round(err_sun, 7), "earth": round(err_earth, 7)},
        "generated": dt.datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),
    }
    out = os.path.join(ROOT, "data", "spice_table.js")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("/* Generated by tools/build_spice_table.py - do not edit. */\n")
        f.write("window.SPICE_TABLE = " + json.dumps(meta) + ";\n")
        f.write('window.SPICE_TABLE.b64 = "' + base64.b64encode(table.tobytes()).decode("ascii") + '";\n')
    print(json.dumps(meta, indent=1))
    print("wrote %s (%.2f MB)" % (out, os.path.getsize(out) / 1e6))


if __name__ == "__main__":
    main()
