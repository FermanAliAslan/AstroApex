"""Build data/moon_texture.js: the Moon map the 3D globe uses, embedded so the site needs no network.

Source: NASA Moon Trek, LRO WAC global mosaic (303 ppd, v02), zoom level 3 = 16 x 8 tiles = 4096 x 2048 px,
equirectangular, longitude -180..180 left to right. Stored as one greyscale JPEG in a data URI.

Run:  pip install pillow   then   python tools/build_moon_texture.py
"""
import base64
import io
import os
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TILES = "https://trek.nasa.gov/tiles/Moon/EQ/LRO_WAC_Mosaic_Global_303ppd_v02/1.0.0/default/default028mm/"
ZOOM = 3
QUALITY = 78


def fetch(rc):
    r, c = rc
    req = urllib.request.Request("%s%d/%d/%d.jpg" % (TILES, ZOOM, r, c), headers={"User-Agent": "astroapex-build"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return rc, Image.open(io.BytesIO(resp.read())).convert("L")


def main():
    cols, rows = 2 << ZOOM, 1 << ZOOM
    mosaic = Image.new("L", (cols * 256, rows * 256))
    cells = [(r, c) for r in range(rows) for c in range(cols)]
    with ThreadPoolExecutor(8) as pool:
        for (r, c), tile in pool.map(fetch, cells):
            mosaic.paste(tile, (c * 256, r * 256))
    buf = io.BytesIO()
    mosaic.save(buf, "JPEG", quality=QUALITY, optimize=True)
    out = os.path.join(ROOT, "data", "moon_texture.js")
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("/* Generated by tools/build_moon_texture.py. NASA Moon Trek, LRO WAC global mosaic, %dx%d. */\n" % mosaic.size)
        f.write('window.MOON_TEXTURE = "data:image/jpeg;base64,' + base64.b64encode(buf.getvalue()).decode("ascii") + '";\n')
    print("wrote %s (%.2f MB, %dx%d)" % (out, os.path.getsize(out) / 1e6, mosaic.size[0], mosaic.size[1]))


if __name__ == "__main__":
    sys.exit(main())
